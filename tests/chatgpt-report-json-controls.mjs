const invalid=valid.replace('Recheck\\n','Recheck\n').replace('reply.\\t','reply.\t');
assert.throws(()=>JSON.parse(invalid));assert.equal(JSON.stringify(parse(invalid)),valid);
assert.equal(parse('{"value":"x\u0000y\u0001z"}').value,'x\u0000y\u0001z');
assert.equal(parse('{"value":"literal \\n and escaped \\\" quote"}').value,'literal \n and escaped " quote');
for(const bad of [valid+' trailing prose',valid.slice(0,-1),'{job_id:"not-json"}', '{"a":1,}', '{"value":"bad\\x escape"}']) assert.throws(()=>parse(bad));
const start=source.indexOf('  function parseWorkerReportJson',source.indexOf('async function pageChatgptRuntimeConversationStart('));
const end=source.indexOf('\n\n  if (location.origin',start);assert.ok(end>start);
const gate=vm.runInNewContext('(function(prompt,text){'+source.slice(start,end)+';return applicableWorkerFinal(text);})');
const prompt='JOB ID: `'+job+'`\nruntime_report_version';
assert.equal(gate(prompt,invalid),true);
assert.equal(gate(prompt,valid.replace(job,'job-other')),false);
assert.equal(gate(prompt,'I am checking Reddit.'),false);
assert.equal(gate(prompt,valid.replace('"completed"','"running"')),false);
assert.equal(gate(prompt,valid+' trailing prose'),false);
assert.equal(gate('JOB ID: `'+job+'`\nMATO_JOB_RESULT: '+job,'Finished.\nMATO_JOB_RESULT: '+job),true);
assert.equal(gate('JOB ID: `'+job+'`\nMATO_JOB_RESULT: '+job,'MATO_JOB_RESULT: job-other'),false);
console.log('Report control-character tests passed; exact-job identity, private markers and strict JSON structure preserved.');
